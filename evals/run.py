"""Write docs/eval-results.md: (1) the predictive evaluation computed by `python -m deployrisk.train` (chronological holdout and
leave-one-repo-out, against a lines-changed baseline) and (2) a cross-provider check of the model-written note:
the band must not change, the model must not receive code or file names, and no unclean note may be kept.

    GOOGLE_CLOUD_PROJECT=<proj> .venv/bin/python evals/run.py --providers mock,vertex,openai
"""

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
for line in (ROOT / ".env").read_text().splitlines() if (ROOT / ".env").exists() else []:
    k, _, v = line.partition("=")
    if k and not k.startswith("#") and k != "DEPLOYRISK_LLM":
        os.environ.setdefault(k, v)

from deployrisk.agents import add_note  # noqa: E402
from deployrisk.llm import Budget, make_llm  # noqa: E402
from deployrisk.models import Change, FileChange  # noqa: E402
from deployrisk.score import load_model, score_change  # noqa: E402

CASES = {
    "docs": Change(
        files=[FileChange(path="README.md", added=3, deleted=1)], message="docs: fix typo"
    ),
    "small fix": Change(
        files=[
            FileChange(path="src/private_billing/engine.py", added=6, deleted=2),
            FileChange(path="tests/test_engine.py", added=12),
        ],
        message="fix: rounding in zeta pricing",
    ),
    "iam change": Change(
        files=[FileChange(path="infra/iam.tf", added=30, deleted=5)], message="grant deploy role"
    ),
    "large refactor": Change(
        files=[FileChange(path=f"src/m{i}.py", added=60, deleted=20) for i in range(40)],
        message="refactor",
    ),
}
SECRET_BITS = ["private_billing", "zeta", "engine.py", "iam.tf"]


class Spy:
    def __init__(self, llm):
        self._llm, self.sent = llm, []
        self.name, self.model = llm.name, llm.model

    async def complete_json(self, system, user, max_tokens=1200):
        self.sent.append(user)
        return await self._llm.complete_json(system, user, max_tokens)


async def llm_rows(providers):
    model = load_model("diff_only")
    rows = []
    for prov in providers:
        kept = rejected = leaks = band_changes = calls = 0
        cost = 0.0
        for c in CASES.values():
            base = score_change(c, model, "diff_only")
            spy = Spy(make_llm(prov))
            s = await add_note(score_change(c, model, "diff_only"), spy, Budget())
            calls += len(spy.sent)
            leaks += sum(any(b in x for b in SECRET_BITS) for x in spy.sent)
            kept += bool(s.note)
            rejected += len(s.dropped)
            band_changes += s.band != base.band
            cost += sum(t.cost_usd for t in s.trace)
        rows.append((f"{spy.name}/{spy.model}", kept, rejected, leaks, band_changes, calls, cost))
        print(rows[-1], flush=True)
    return rows


def main(providers, out):
    ev = json.loads((ROOT / "deployrisk" / "data" / "eval.json").read_text())
    L = [
        "# Evaluation results",
        "",
        "## 1. Does the score predict follow-up fixes?",
        "",
        "Label: a commit is positive if a later commit whose message says fix/revert/hotfix/regression touches one of the same files within 30 commits and 14 days (a proxy; see README). "
        "Trained and tested on the full history of five public repositories (flask, requests, click, werkzeug, httpx). Generated by `python -m deployrisk.train` and `evals/run.py`.",
        "",
    ]
    for variant, title in (
        ("diff_only", "Diff-only model (what the hosted service uses)"),
        ("full", "Full model (adds repository history: hotspots, author familiarity)"),
    ):
        L += [
            f"### {title}",
            "",
            "**Chronological holdout**: train on the earliest 70% of each repo, test on the latest 30%.",
            "",
            "| repo | test commits | base rate | AUC | lines-changed baseline AUC | lift in top 10% | Brier | Brier of the base rate |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for repo, m in ev[variant]["chronological"].items():
            L.append(
                f"| {repo.strip('_')} | {m['n']} | {m['base_rate']:.1%} | {m['auc']:.3f} | {m['auc_lines_only'] if m['auc_lines_only'] else '-'} | {m['lift_at_10pct']:.2f}x | {m['brier']:.4f} | {m['brier_baseline']:.4f} |"
            )
        L += [
            "",
            "**Leave-one-repo-out**: train on the other four repos, test on the held-out repo (never seen).",
            "",
            "| held-out repo | commits | base rate | AUC | lines-changed baseline AUC | lift in top 10% | Brier | Brier of the base rate |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for repo, m in ev[variant]["leave_one_repo_out"].items():
            L.append(
                f"| {repo} | {m['n']} | {m['base_rate']:.1%} | {m['auc']:.3f} | {m['auc_lines_only']:.3f} | {m['lift_at_10pct']:.2f}x | {m['brier']:.4f} | {m['brier_baseline']:.4f} |"
            )
        L.append("")
    L += [
        "## 2. The model-written note",
        "",
        "Four changes per provider. The band must not change, the model must never receive code or file names, and no unclean note may be kept.",
        "",
        "| provider | notes kept | notes rejected | payloads containing code or paths | band changes | model calls | cost |",
        "|---|---|---|---|---|---|---|",
    ]
    bad = 0
    for name, kept, rej, leaks, bc, calls, cost in asyncio.run(llm_rows(providers)):
        bad += leaks + bc
        L.append(f"| {name} | {kept} | {rej} | {leaks} | {bc} | {calls} | ${cost:.4f} |")
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}; violations: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--providers", default="mock")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "eval-results.md")
    a = ap.parse_args()
    sys.exit(main(a.providers.split(","), a.out))
